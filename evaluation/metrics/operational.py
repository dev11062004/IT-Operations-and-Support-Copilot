"""Operational metrics: Retrieval latency, model generation latency, token counts, and cost estimation."""

import logging
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field

logger = logging.getLogger("OperationalMetrics")

# Standard pricing table in USD per 1,000,000 tokens
MODEL_PRICING_PER_1M = {
    # Chat Models (Prompt, Completion)
    "gpt-4o-mini": {"input": 0.150, "output": 0.600},
    "gpt-4o": {"input": 2.500, "output": 10.000},
    "gpt-4-turbo": {"input": 10.000, "output": 30.000},
    "gpt-3.5-turbo": {"input": 0.500, "output": 1.500},
    # Embedding Models (Input only)
    "text-embedding-3-small": {"input": 0.020, "output": 0.0},
    "text-embedding-3-large": {"input": 0.130, "output": 0.0},
    "text-embedding-ada-002": {"input": 0.100, "output": 0.0},
}


class OperationalMetrics(BaseModel):
    """Container tracking operational latency, throughput, token counts, and financial cost."""
    retrieval_latency_ms: float = Field(0.0, description="Retrieval tool execution latency in ms")
    generation_latency_ms: float = Field(0.0, description="Model generation and reasoning latency in ms")
    total_latency_ms: float = Field(0.0, description="End-to-end request latency in ms")
    prompt_tokens: int = Field(0, description="Number of input prompt tokens")
    completion_tokens: int = Field(0, description="Number of generated output tokens")
    total_tokens: int = Field(0, description="Total tokens consumed")
    estimated_cost_usd: float = Field(0.0, description="Estimated monetary cost in USD")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Diagnostic timing metadata")


def estimate_tokens(text: str, model_name: str = "gpt-4o-mini") -> int:
    """Accurately count or estimate tokens for a given string."""
    if not text:
        return 0
    try:
        import tiktoken
        try:
            encoding = tiktoken.encoding_for_model(model_name)
        except KeyError:
            encoding = tiktoken.get_encoding("cl100k_base")
        return len(encoding.encode(text))
    except Exception:
        # Fallback heuristic: 1 token ≈ 4 characters
        return max(1, len(text) // 4)


def compute_cost_usd(
    model_name: str,
    prompt_tokens: int,
    completion_tokens: int,
    embedding_model: Optional[str] = None,
    embedding_tokens: int = 0,
) -> float:
    """Calculate monetary cost in USD based on official token pricing tables.

    Args:
        model_name: Main chat model name (e.g. 'gpt-4o-mini').
        prompt_tokens: Number of prompt/input tokens.
        completion_tokens: Number of completion/output tokens.
        embedding_model: Optional embedding model name.
        embedding_tokens: Optional embedding tokens used during retrieval.

    Returns:
        Estimated cost in USD rounded to 6 decimal places.
    """
    clean_model = model_name.lower().split("/")[-1]
    pricing = MODEL_PRICING_PER_1M.get(clean_model, MODEL_PRICING_PER_1M["gpt-4o-mini"])

    cost_prompt = (prompt_tokens / 1_000_000.0) * pricing["input"]
    cost_completion = (completion_tokens / 1_000_000.0) * pricing["output"]

    cost_embed = 0.0
    if embedding_model and embedding_tokens > 0:
        clean_embed = embedding_model.lower().split("/")[-1]
        embed_pricing = MODEL_PRICING_PER_1M.get(clean_embed, MODEL_PRICING_PER_1M["text-embedding-3-small"])
        cost_embed = (embedding_tokens / 1_000_000.0) * embed_pricing["input"]

    total = cost_prompt + cost_completion + cost_embed
    return round(total, 6)


def extract_operational_metrics(
    query: str,
    generated_answer: str,
    retrieval_latency_ms: float = 0.0,
    model_latency_ms: float = 0.0,
    total_latency_ms: float = 0.0,
    context_text: str = "",
    model_name: str = "gpt-4o-mini",
    embedding_model: str = "text-embedding-3-small",
    token_usage_dict: Optional[Dict[str, int]] = None,
) -> OperationalMetrics:
    """Assemble complete operational metrics from execution trace.

    Args:
        query: User input prompt.
        generated_answer: Output text generated by model.
        retrieval_latency_ms: Time spent in retrieval.
        model_latency_ms: Time spent in LLM.
        total_latency_ms: End-to-end latency.
        context_text: Text of retrieved context chunks.
        model_name: LLM model name.
        embedding_model: Embedding model name.
        token_usage_dict: Optional dict containing actual prompt_tokens/completion_tokens.

    Returns:
        OperationalMetrics instance.
    """
    if token_usage_dict and "prompt_tokens" in token_usage_dict:
        p_tokens = int(token_usage_dict.get("prompt_tokens", 0))
        c_tokens = int(token_usage_dict.get("completion_tokens", 0))
    else:
        # Estimate from prompt (query + context) and answer
        full_input = f"{query}\n{context_text}"
        p_tokens = estimate_tokens(full_input, model_name=model_name)
        c_tokens = estimate_tokens(generated_answer, model_name=model_name)

    tot_tokens = p_tokens + c_tokens
    embed_tokens = estimate_tokens(query, model_name=embedding_model)

    cost = compute_cost_usd(
        model_name=model_name,
        prompt_tokens=p_tokens,
        completion_tokens=c_tokens,
        embedding_model=embedding_model,
        embedding_tokens=embed_tokens,
    )

    tot_lat = total_latency_ms if total_latency_ms > 0 else (retrieval_latency_ms + model_latency_ms)

    return OperationalMetrics(
        retrieval_latency_ms=round(retrieval_latency_ms, 2),
        generation_latency_ms=round(model_latency_ms, 2),
        total_latency_ms=round(tot_lat, 2),
        prompt_tokens=p_tokens,
        completion_tokens=c_tokens,
        total_tokens=tot_tokens,
        estimated_cost_usd=cost,
    )
